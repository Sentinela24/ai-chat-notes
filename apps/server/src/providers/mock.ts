import { setTimeout as sleep } from 'node:timers/promises';
import { ProviderError } from './errors';
import type { CompletionParams, LLMProvider, ProviderEvent } from './types';

/**
 * A fake LLM that streams a deterministic Markdown reply token by token.
 *
 * It lets the whole app (and the Playwright test) run without an API key, and
 * it can simulate the failure modes that are hard to trigger on demand with a
 * real model. Put one of these in a message:
 *
 *   /error   fail halfway through the stream (retryable)
 *   /fail    fail before the first token
 *   /slow    stream 8x slower (handy for testing Stop)
 *   /refuse  end with a refusal stop reason
 *   /long    a long reply (for scroll behaviour)
 */
export interface MockOptions {
  /** Delay between tokens. 0 in tests. */
  delayMs?: number;
}

export const MOCK_TRIGGERS = ['/error', '/fail', '/slow', '/refuse', '/long'] as const;

export function createMockProvider({ delayMs = 30 }: MockOptions = {}): LLMProvider {
  return {
    name: 'mock',
    model: 'mock-1',
    async *stream(params: CompletionParams, signal: AbortSignal): AsyncGenerator<ProviderEvent> {
      const prompt = params.messages.at(-1)?.content ?? '';
      const has = (trigger: string) => prompt.toLowerCase().includes(trigger);
      const delay = has('/slow') ? delayMs * 8 : delayMs;

      if (has('/fail')) {
        await sleep(delay, undefined, { signal });
        throw new ProviderError(
          'overloaded',
          'The model is overloaded right now (simulated by mock mode).',
        );
      }

      const refusing = has('/refuse');
      const text = refusing ? REFUSAL_TEXT : buildReply(params, prompt, has('/long'));
      const tokens = tokenize(text);
      const failAt = has('/error') ? Math.floor(tokens.length / 3) : -1;

      for (const [i, token] of tokens.entries()) {
        await sleep(delay, undefined, { signal });
        if (i === failAt) {
          throw new ProviderError(
            'upstream',
            'The connection to the model dropped (simulated by mock mode).',
          );
        }
        yield { type: 'delta', text: token };
      }

      yield {
        type: 'done',
        stopReason: refusing ? 'refusal' : 'end_turn',
        usage: { inputTokens: estimateTokens(params), outputTokens: tokens.length },
      };
    },
  };
}

/** Splits text into word-sized chunks that keep their trailing whitespace, like real LLM tokens roughly do. */
export function tokenize(text: string): string[] {
  return text.match(/\s*\S+\s*/g) ?? [];
}

function estimateTokens(params: CompletionParams): number {
  const chars = params.system.length + params.messages.reduce((n, m) => n + m.content.length, 0);
  return Math.ceil(chars / 4);
}

const REFUSAL_TEXT = "I'm not able to help with that request (simulated refusal).";

function buildReply(params: CompletionParams, prompt: string, long: boolean): string {
  switch (params.task) {
    case 'summarise':
      return summarise(prompt);
    case 'rewrite':
      return rewrite(prompt);
    case 'chat':
      return long ? chatReply(prompt) + '\n\n' + LONG_TAIL : chatReply(prompt);
  }
}

function chatReply(prompt: string): string {
  const quoted = prompt.length > 80 ? `${prompt.slice(0, 77).trimEnd()}...` : prompt;
  return `Here's a **mock** reply to: "${quoted}"

This response is generated by the server's mock provider and streamed token by token over Server-Sent Events, so the app works without an API key.

### Things to try
- Type \`/slow\` to slow the stream down, then press **Stop** (or Esc)
- Type \`/error\` to simulate a failure halfway through, then **Retry**
- Type \`/refuse\` to see how a model refusal is shown
- Type \`/long\` for a long reply

\`\`\`ts
for await (const event of streamChat(messages, signal)) {
  if (event.type === 'delta') append(event.text);
}
\`\`\`

| Event   | Meaning               |
| ------- | --------------------- |
| \`delta\` | a chunk of text       |
| \`done\`  | the stream finished   |
| \`error\` | something went wrong  |`;
}

const LONG_TAIL = Array.from(
  { length: 12 },
  (_, i) =>
    `${i + 1}. Paragraph ${i + 1} of a long answer. Streaming UIs should keep the latest text in view while the user is at the bottom, but must not yank the scroll position if they have scrolled up to read something earlier.`,
).join('\n');

function extractPassage(prompt: string): string {
  const match = /<passage>([\s\S]*?)<\/passage>/.exec(prompt);
  return (match?.[1] ?? prompt).trim();
}

function summarise(prompt: string): string {
  const passage = extractPassage(prompt);
  const words = passage.split(/\s+/).filter(Boolean);
  const gist = words.slice(0, Math.max(8, Math.ceil(words.length * 0.3))).join(' ');
  return `**Summary (mock):** ${gist}${words.length > 8 ? '...' : ''}`;
}

function rewrite(prompt: string): string {
  const passage = extractPassage(prompt);
  const sentences = passage
    .replace(/\s+/g, ' ')
    .split(/(?<=[.!?])\s+/)
    .map((s) => s.charAt(0).toUpperCase() + s.slice(1));
  return `${sentences.join(' ')} *(rewritten by mock mode)*`;
}
