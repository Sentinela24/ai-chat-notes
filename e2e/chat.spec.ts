import AxeBuilder from '@axe-core/playwright';
import { expect, test, type Page } from '@playwright/test';

/**
 * End-to-end: the streaming chat flow against the real server in mock mode.
 * Browser -> Vite proxy -> Hono -> mock provider -> SSE -> parser -> store -> UI.
 */

const composer = (page: Page) => page.getByRole('textbox', { name: 'Message' });
const lastReply = (page: Page) => page.getByRole('article', { name: 'Assistant replied' }).last();

async function send(page: Page, text: string) {
  await composer(page).fill(text);
  await composer(page).press('Enter');
}

test.beforeEach(async ({ page }) => {
  await page.goto('/');
  // Start from a clean slate (state is persisted in localStorage).
  await page.evaluate(() => localStorage.clear());
  await page.reload();
  await expect(page.getByText('Mock mode')).toBeVisible();
});

test('streams a reply token by token and renders Markdown', async ({ page }) => {
  await send(page, 'What is SSE?');

  await expect(page.getByRole('article', { name: 'You said' })).toHaveText('What is SSE?');
  const reply = lastReply(page);

  // While streaming: busy, Stop available, and text arrives in pieces.
  await expect(reply).toHaveAttribute('aria-busy', 'true');
  await expect(page.getByRole('button', { name: 'Stop generating' })).toBeVisible();
  await expect(reply).toContainText("Here's a mock reply");
  const partialLength = (await reply.innerText()).length;

  // Finished: Markdown rendered (heading, code block, table), actions shown.
  await expect(reply).toHaveAttribute('aria-busy', 'false', { timeout: 15_000 });
  expect((await reply.innerText()).length).toBeGreaterThan(partialLength);
  await expect(reply.getByRole('heading', { name: 'Things to try' })).toBeVisible();
  await expect(reply.locator('pre code')).toContainText('for await');
  await expect(reply.getByRole('table')).toBeVisible();
  await expect(page.getByRole('button', { name: 'Send message' })).toBeVisible();

  // Screen-reader narration ended with the outcome.
  await expect(page.locator('[aria-live="polite"]')).toContainText('Response complete.');

  // Survives a reload (persisted to localStorage).
  await page.reload();
  await expect(lastReply(page)).toContainText('Things to try');
});

test('stop keeps the partial reply and returns focus to the composer', async ({ page }) => {
  await send(page, 'Go slowly /slow');
  const reply = lastReply(page);
  await expect(reply).toContainText("Here's a");

  await page.keyboard.press('Escape');

  await expect(reply.getByText(/Stopped/)).toBeVisible();
  await expect(reply).toHaveAttribute('aria-busy', 'false');
  await expect(composer(page)).toBeFocused();
  await expect(page.getByRole('button', { name: 'Retry' })).toBeVisible();
});

test('a mid-stream failure shows the error and can be retried', async ({ page }) => {
  await send(page, 'Break please /error');

  const reply = lastReply(page);
  await expect(reply.getByText(/connection to the model dropped/)).toBeVisible({ timeout: 15_000 });
  await expect(reply).toContainText("Here's a"); // partial text is kept

  await page.getByRole('button', { name: 'Retry' }).click();
  // The failed reply is replaced by a new attempt (the mock fails deterministically again).
  await expect(page.getByRole('article', { name: 'Assistant replied' })).toHaveCount(1);
  await expect(lastReply(page).getByText(/connection to the model dropped/)).toBeVisible({
    timeout: 15_000,
  });
});

test('a reply can be saved to notes and opened in the editor', async ({ page }) => {
  await send(page, 'Note-worthy answer');
  await expect(lastReply(page)).toHaveAttribute('aria-busy', 'false', { timeout: 15_000 });

  await page.getByRole('button', { name: 'Save to notes' }).click();
  await page.getByRole('button', { name: 'Open' }).click();

  await expect(page.getByRole('button', { name: 'Notes', exact: true })).toHaveAttribute(
    'aria-current',
    'page',
  );
  const editor = page.getByRole('textbox', { name: 'Note content' });
  await expect(editor).toContainText('This response is generated by');
  await expect(editor.getByRole('heading', { name: 'Things to try' })).toBeVisible();
});

test('summarise streams a suggestion that can be inserted into the note', async ({ page }) => {
  await page.getByRole('button', { name: 'Notes', exact: true }).click();
  await page.getByRole('button', { name: 'Create a note' }).click();
  const editor = page.getByRole('textbox', { name: 'Note content' });
  await editor.click();
  await editor.pressSequentially('Streaming UIs render tokens as they arrive from the server.');
  await page.keyboard.press('ControlOrMeta+a');

  await page.getByRole('button', { name: 'Summarise' }).click();
  const panel = page.getByRole('region', { name: 'AI suggestion' });
  await expect(panel.getByRole('status')).toContainText('Suggestion ready');
  await expect(page.getByRole('button', { name: 'Insert below' })).toBeFocused();

  await page.keyboard.press('Enter');
  await expect(panel).toBeHidden();
  await expect(editor).toContainText('Summary (mock):');
});

test('chat view has no serious accessibility violations', async ({ page }) => {
  await send(page, 'Accessibility check');
  await expect(lastReply(page)).toHaveAttribute('aria-busy', 'false', { timeout: 15_000 });

  const results = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa']).analyze();
  const serious = results.violations.filter((v) =>
    ['serious', 'critical'].includes(v.impact ?? ''),
  );
  expect(serious, JSON.stringify(serious, null, 2)).toEqual([]);
});
